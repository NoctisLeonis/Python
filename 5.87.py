количество = 0

# Перебираем сотни (от 1 до 5, но для 500 особый случай)
for сотни in range(1, 6):
    for десятки in range(0, 10):
        for единицы in range(0, 10):
            # Составляем число
            число = сотни * 100 + десятки * 10 + единицы

            # Проверяем, что число в нужном диапазоне
            if 100 <= число <= 500:
                # Проверяем сумму цифр
                if сотни + десятки + единицы == 15:
                    количество += 1
                    print(число, end=" ")

print(f"\n\nКоличество чисел: {количество}")