n = int(input("Введите число n: "))
print(f"\nИщем первое число из последовательности квадратов, большее {n}")
print("=" * 50)
# Находим целую часть квадратного корня
sqrt_n = int(n ** 0.5)  # ** - возведение в степень
print(f"√{n} ≈ {n ** 0.5:.2f}")
print(f"Целая часть √{n} = {sqrt_n}")
# Следующее целое число
next_k = sqrt_n + 1
# Искомый квадрат
result = next_k ** 2
print(f"Следующее целое число: {next_k}")
print(f"Его квадрат: {next_k}² = {result}")
print("-" * 50)
print(f"Результат: {result}")