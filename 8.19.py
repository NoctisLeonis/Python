print("=" * 60)
# Первые два числа
a = 1  # F₁
b = 1  # F₂
sum_fib = a + b  # начинаем сумму с первых двух чисел
print(f"F₁ = {a}")
print(f"F₂ = {b}")
# Генерируем следующие числа
while True:
    c = a + b  # следующее число Фибоначчи
    if c > 1000:
        break
    print(f"F = {c}")
    sum_fib += c
    a, b = b, c  # сдвигаемся вперёд
print("-" * 60)
print(f"Сумма всех чисел Фибоначчи ≤ 1000: {sum_fib}")