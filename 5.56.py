import math
# Пределы интегрирования
a = 0          # Нижний предел
b = math.pi    # Верхний предел (π ≈ 3.14159)
# Количество разбиений (чем больше, тем точнее)
n = 1000
# Шаг разбиения
h = (b - a) / n
# Переменная для накопления площади
площадь = 0
# Вычисляем площадь методом прямоугольников
for i in range(n):
    x = a + i * h  # Текущая координата x
    y = math.sin(x)  # Значение функции в этой точке
    площадь += y * h  # Добавляем площадь прямоугольника
print(f"Приближенная площадь арки синусоиды: {площадь}")
print(f"Точное значение: 2")
print(f"Погрешность: {abs(2 - площадь)}")