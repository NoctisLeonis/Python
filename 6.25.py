import math
n = int(input("Введите натуральное число: "))
# Проверяем делители от 2 до корня из n
divisor = 2
limit = int(math.sqrt(n))  # целая часть квадратного корня
while divisor <= limit:
    if n % divisor == 0:
        print(f"Наименьший делитель: {divisor}")
        break  # нашли, выходим из цикла
    divisor += 1
else:
    # Если цикл завершился без break, значит делителей не найдено
    # В этом случае число простое, и его наименьший делитель — оно само
    print(f"Наименьший делитель: {n} (число простое)")