n = int(input("Введите трехзначное число: "))

# Разбираем число на цифры
# 1-я цифра: делим на 100 нацело (например, 345 // 100 = 3)
digit1 = n // 100
# 2-я цифра: сначала убираем сотни, потом берем десятки (345 % 100 = 45; 45 // 10 = 4)
digit2 = (n % 100) // 10
# 3-я цифра: остаток от деления на 10 (345 % 10 = 5)
digit3 = n % 10

# а) Первая или последняя
if digit1 > digit3:
    print("Первая цифра больше последней")
elif digit3 > digit1:
    print("Последняя цифра больше первой")
else:
    print("Первая и последняя цифры равны")

# б) Первая или вторая
if digit1 > digit2:
    print("Первая цифра больше второй")
elif digit2 > digit1:
    print("Вторая цифра больше первой")
else:
    print("Первая и вторая цифры равны")

# в) Вторая или последняя
if digit2 > digit3:
    print("Вторая цифра больше последней")
elif digit3 > digit2:
    print("Последняя цифра больше второй")
else:
    print("Вторая и последняя цифры равны")
