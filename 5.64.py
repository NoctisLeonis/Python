# Вводим семизначное число
число = int(input("Введите семизначное число: "))
# Сохраняем исходное число для вывода
исходное = число
# Переменная для хранения перевернутого числа
перевернутое = 0
# Пока число не станет равно 0
while число > 0:
    # Берем последнюю цифру
    цифра = число % 10
    # Добавляем цифру к перевернутому числу
    перевернутое = перевернутое * 10 + цифра
    # Убираем последнюю цифру из исходного числа
    число = число // 10
print(f"Исходное число: {исходное}")
print(f"Число справа налево: {перевернутое}")