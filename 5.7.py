# Цена одной штуки
цена_за_штуку = 20.4

# Выводим заголовок таблицы
print("Количество | Стоимость (руб)")
print("-" * 30)  # Разделительная линия

# Цикл от 2 до 20 включительно
for количество in range(2, 21):
    # Рассчитываем стоимость
    стоимость = количество * цена_за_штуку

    # Выводим строку таблицы с форматированием
    print(f"{количество:^10} | {стоимость:^15.2f}")